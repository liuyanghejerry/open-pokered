pub(crate) fn line_offset(move_id: u8, player_is_attacker: bool, phase: u8, y: u32) -> i8 {
    let segments: &[u32] = match (move_id, player_is_attacker) {
        (94, true) => &PSYCHIC_PLAYER,
        (94, false) => &PSYCHIC_ENEMY,
        (101, true) => &NIGHT_SHADE_PLAYER,
        (101, false) => &NIGHT_SHADE_ENEMY,
        (149, true) => &PSYWAVE_PLAYER,
        (149, false) => &PSYWAVE_ENEMY,
        _ => return LINE_OFFSETS[(usize::from(phase) + y as usize) % 32],
    };
    debug_assert!(phase < 127);
    debug_assert!(y < 144);
    let mut table_start = 0usize;
    for &packed in segments {
        let entry_phase = (packed >> 13) as u8;
        if entry_phase > phase {
            break;
        }
        if entry_phase == phase {
            let first_scanline = (packed >> 5) & 0xff;
            if first_scanline > y {
                break;
            }
            table_start = (packed & 0x1f) as usize;
        }
    }
    LINE_OFFSETS[(table_start + 2 * y as usize) % 32]
}
